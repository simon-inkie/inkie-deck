/**
 * Running a document's own blocks in a live container.
 *
 * `runIn` in docker.mjs is a one-shot `docker run`, which is right for a
 * command that finishes and wrong for an installation guide: half the point of
 * INSTALL.md is a server that starts and stays up, and a probe against it has
 * to come from OUTSIDE the container's network namespace, because a curl run
 * inside passes against a loopback-only bind and proves nothing. So this file
 * keeps a container alive, publishes a port, and executes the extracted blocks
 * inside it.
 *
 * The isolation guarantees of docker.mjs are kept: no bind mount of the
 * working copy, no inherited environment, `--rm` on exit. The only thing that
 * crosses is the extracted blocks, copied in as files and sourced unmodified.
 *
 * WHY SOURCING RATHER THAN A SHELL PER BLOCK: a reader types these into one
 * terminal, so `cd`, `export ME=...` and `export AGENT_NAME=...` in an early
 * block are still in effect for a later one. A block-per-exec runner would
 * quietly need every block to re-establish its own environment, which is a
 * document nobody wrote.
 */
import * as fs from "node:fs";
import * as net from "node:net";
import * as os from "node:os";
import * as path from "node:path";
import { docker } from "./docker.mjs";
import { exec, must, RigError, stripAnsi } from "./exec.mjs";

/** Long enough for apt, a Node install, a pnpm install and a production build. */
const DRIVER_TIMEOUT_MS = 20 * 60 * 1000;

/**
 * Start a detached container with one published port.
 *
 * @param {{ image: string, name: string, containerPort: number }} spec
 * @returns {Promise<{ name: string, hostPort: number }>}
 */
export async function startContainer({ image, name, containerPort }) {
  removeContainer(name);
  const hostPort = await freeHostPort();
  // Published on 127.0.0.1 only. The rig must not open a port on whatever
  // network the machine running it happens to be attached to, least of all one
  // serving an application with no authentication.
  must("docker", [
    "run",
    "-d",
    "--name",
    name,
    "-p",
    `127.0.0.1:${hostPort}:${containerPort}`,
    image,
    "sleep",
    "infinity",
  ]);
  return { name, hostPort };
}

/** @param {string} name */
export function removeContainer(name) {
  docker(["rm", "-f", name]);
}

/**
 * Copy the extracted blocks in and source them in order, in one shell.
 *
 * @param {{
 *   name: string,
 *   blocks: import("./fenced.mjs").FencedBlock[],
 *   longRunning?: Record<string, { waitSeconds: number }>,
 * }} spec
 */
export function runBlocks({ name, blocks, longRunning = {} }) {
  const staging = fs.mkdtempSync(path.join(fs.realpathSync(os.tmpdir()), "rig-doc-"));
  try {
    const driver = ["# generated by rig/lib/docrun.mjs; the block files are verbatim", "cd /src"];
    blocks.forEach((block, index) => {
      const file = `${String(index).padStart(2, "0")}.sh`;
      // VERBATIM. Nothing is prefixed, appended, quoted or normalised: the
      // bytes between the fences are the bytes that run.
      fs.writeFileSync(path.join(staging, file), block.text, "utf8");
      driver.push(`echo "###BEGIN ${block.id}"`);
      const long = longRunning[block.id];
      if (long) {
        // A block the document says never returns. Backgrounded in a subshell
        // so the driver can carry on, with its output kept for the report, and
        // then the wait a reader would spend watching it come up.
        driver.push(`( . /doc/${file} ) > /doc/${file}.log 2>&1 &`);
        driver.push(`echo "###BG ${block.id} $!"`);
        driver.push(`sleep ${long.waitSeconds}`);
      } else {
        driver.push(`. /doc/${file}`);
        driver.push(`echo "###EXIT ${block.id} $?"`);
      }
    });
    driver.push('echo "###DRIVER-END"');
    fs.writeFileSync(path.join(staging, "driver.sh"), `${driver.join("\n")}\n`, "utf8");

    must("docker", ["exec", name, "mkdir", "-p", "/doc"]);
    must("docker", ["cp", `${staging}/.`, `${name}:/doc`]);
    const result = exec("docker", ["exec", name, "bash", "/doc/driver.sh"], {
      timeout: DRIVER_TIMEOUT_MS,
    });
    return { ...parseBlockMarkers(result.output, blocks), raw: result.output, driver: driver.join("\n") };
  } finally {
    fs.rmSync(staging, { recursive: true, force: true });
  }
}

/**
 * Exit codes and per-block output, keyed by block id.
 *
 * A block with no marker reads as `null`, never as 0. The absent-marker case
 * means the driver never got that far, which is a stronger failure than a
 * non-zero exit and must never be coalesced into a pass.
 *
 * @param {string} rawOutput
 * @param {import("./fenced.mjs").FencedBlock[]} blocks
 */
export function parseBlockMarkers(rawOutput, blocks) {
  const output = stripAnsi(rawOutput);
  /** @type {Record<string, number|null>} */
  const exits = {};
  /** @type {Record<string, string|null>} */
  const backgrounded = {};
  /** @type {Record<string, string>} */
  const blockOutput = {};
  for (const block of blocks) {
    exits[block.id] = null;
    backgrounded[block.id] = null;
  }
  for (const match of output.matchAll(/^###EXIT (\S+) (\d+)$/gm)) {
    exits[match[1]] = Number(match[2]);
  }
  for (const match of output.matchAll(/^###BG (\S+) (\d+)$/gm)) {
    backgrounded[match[1]] = match[2];
  }
  for (const block of blocks) {
    const begin = output.indexOf(`###BEGIN ${block.id}\n`);
    if (begin < 0) continue;
    const from = begin + `###BEGIN ${block.id}\n`.length;
    const nextMarker = output.slice(from).search(/^###(BEGIN|EXIT|BG|DRIVER-END)/m);
    blockOutput[block.id] = (nextMarker < 0 ? output.slice(from) : output.slice(from, from + nextMarker)).trim();
  }
  return { exits, backgrounded, blockOutput, completed: output.includes("###DRIVER-END") };
}

/**
 * Run an arbitrary script inside a live container.
 *
 * For the rig's OWN checks and negative controls, never for anything the
 * document claims: what the document claims is executed from the document.
 *
 * @param {string} name @param {string} script
 */
export function execIn(name, script) {
  return exec("docker", ["exec", name, "bash", "-c", script], { timeout: 5 * 60 * 1000 });
}

/**
 * Fetch from OUTSIDE the container's network namespace.
 *
 * The one probe shape that can tell a published port from a loopback-only
 * bind. A curl inside the container answers 200 in both cases, which is how a
 * container image can be shipped that nothing outside it can ever reach.
 *
 * @param {string} url
 * @param {{ timeoutMs?: number }} [options]
 * @returns {Promise<{ reached: boolean, status: number|null, body: string, error: string|null }>}
 */
export async function fetchOutside(url, options = {}) {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), options.timeoutMs ?? 15000);
  try {
    const response = await fetch(url, { signal: controller.signal, redirect: "manual" });
    const body = await response.text();
    return { reached: true, status: response.status, body, error: null };
  } catch (error) {
    // A refused connection is a RESULT here, not an accident: it is what a
    // loopback bind looks like from outside, and one of the runs requires it.
    return { reached: false, status: null, body: "", error: String(error?.cause?.code ?? error?.message ?? error) };
  } finally {
    clearTimeout(timer);
  }
}

/**
 * Poll until the application answers, or give up.
 *
 * @param {string} url @param {{ attempts?: number, delayMs?: number }} [options]
 */
export async function waitForHttp(url, options = {}) {
  const attempts = options.attempts ?? 30;
  const delayMs = options.delayMs ?? 2000;
  let last = { reached: false, status: null, body: "", error: "never attempted" };
  for (let attempt = 0; attempt < attempts; attempt += 1) {
    last = await fetchOutside(url, { timeoutMs: 10000 });
    if (last.reached && last.status === 200) return { ...last, attempts: attempt + 1 };
    await new Promise((resolve) => setTimeout(resolve, delayMs));
  }
  return { ...last, attempts };
}

/** An unused localhost port, asked of the kernel rather than guessed. */
function freeHostPort() {
  return new Promise((resolve, reject) => {
    const server = net.createServer();
    server.on("error", reject);
    server.listen(0, "127.0.0.1", () => {
      const address = server.address();
      if (typeof address === "string" || address === null) {
        server.close();
        reject(new RigError("could not obtain a free host port"));
        return;
      }
      const { port } = address;
      server.close(() => resolve(port));
    });
  });
}
